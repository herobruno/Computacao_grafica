static inline void draw_character(const GLfloat &x, const GLfloat &y, char character) {
  if (character < 0 || character >= kCharacterQuantity) {
    return;
  }

  glBegin(GL_QUADS);
  for (int character_row = 0; character_row < kCharacterHeight; character_row++) {
    uint8_t character_data_mask = (1 << (kCharacterWidth - 1));
    for (int character_column = 0; character_column < kCharacterWidth; character_column++) {
      if ((kFontData[character][character_row] & character_data_mask) != 0) {
        GLfloat character_x = x + character_column;
        GLfloat character_y = y + (kCharacterHeight - 1 - character_row);
        glVertex2f(character_x, character_y);
        glVertex2f(character_x + 1, character_y);
        glVertex2f(character_x + 1, character_y + 1);
        glVertex2f(character_x, character_y + 1);
      }
      character_data_mask >>= 1;
    }
  }
  glEnd();
}

static inline void draw_text(const GLfloat &x, const GLfloat &y, const std::string &text) {
  GLfloat character_x = x;
  for (char text_character : text) {
    draw_character(character_x, y, text_character);
    character_x += (kCharacterWidth + 1);
  }
}

